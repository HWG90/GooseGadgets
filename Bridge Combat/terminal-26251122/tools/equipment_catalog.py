"""Generate src/equipment_packages.lua: the packages whose units ship combat can leave in the world.

Input: a pkgscan listing of the game's data directory (Linux HD2 Mods builds/26251122/maps/bridge/pkgscan.go, filediver's
reader): `PACKAGE <hash> "<name>" items=N units=M`, then one `unit <hash> <name>` line per unit resource. Every package
that holds a helldiver equipment unit (weapons, attachments, throwables, backpacks) is a candidate. Kept: the generated
loadout packages by name, and any package of at most 600 items whose named units are all helldiver equipment or weapon
effects (casings). That covers the unnamed customization attachment packages (a magazine attachment is a one-unit
package of its own) and loadout packages whose names are not in the hash lists. Mission, stamp, objective and the ship
content packages are left out: they also carry equipment units, but none of them is unloaded by an Armory swap.

Usage: python3 -I equipment_catalog.py LISTING OUT.lua
"""
import sys

EQ, FX = 'content/fac_helldivers/equipment/', 'content/effects/fac_helldivers/weapon/'


def main():
    packages, current = {}, None
    for line in open(sys.argv[1]):
        f = line.split()
        if line.startswith('PACKAGE'):
            current = f[1]; packages[current] = {'name': f[2].strip('"'), 'items': int(f[3].split('=')[1]), 'units': []}
        elif f[:1] == ['unit']:
            packages[current]['units'].append(f[2] if len(f) > 2 else '')
    keep, magazines, covered = [], set(), set()
    for key, p in packages.items():
        named = [u for u in p['units'] if u]
        magazines.update(u for u in named if '/attachment/magazine/' in u)
        if p['name'].startswith('packages/generated/loadout/') or (p['items'] <= 600 and any(u.startswith(EQ) for u in named)
                                                                   and all(u.startswith(EQ) or u.startswith(FX) for u in named)):
            keep.append(int(key, 16)); covered.update(u for u in named if '/attachment/magazine/' in u)
    keep.sort()
    # The three magazine attachment units of the four Armory crashes must be covered.
    for name in ('assaultrifle_drum_magazine_legacy', 'marksmanrifle_standard_drake_magazine', 'vigilance_magazine_standard'):
        assert any(u.endswith('/' + name) for u in covered), name
    with open(sys.argv[2], 'w') as out:
        out.write('-- Generated by native-work/bridge-original/equipment_catalog.py from the game 26251122 data listing.\n'
                  '-- Loadout and customization attachment packages: the units ship combat can leave in the world\n'
                  '-- (dropped magazines, casings, thrown gear) come from these. Package IDs only.\n'
                  'return {stamp=0x6AE0E5FF,packages={\n')
        for i in range(0, len(keep), 6):
            out.write('    ' + ''.join('"%016x",' % k for k in keep[i:i + 6]) + '\n')
        out.write('}}\n')
    print('equipment packages', len(keep), 'of', len(packages), '; magazine units covered', len(covered), 'of', len(magazines),
          sorted(m.rsplit('/', 1)[-1] for m in magazines - covered))


if __name__ == '__main__':
    main()
