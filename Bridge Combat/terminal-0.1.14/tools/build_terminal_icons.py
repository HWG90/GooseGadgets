"""Offline-only icon compiler. Requires Pillow and resvg-py; players need neither.

Compile pinned SVG artwork to vertically merged monochrome rectangle masks.
The existing retained GUI batches these only when a terminal page changes.
"""
from pathlib import Path
import concurrent.futures
import hashlib
import io
import json
import urllib.parse
import urllib.request
import resvg_py
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/terminal-icons'
TREE = json.loads((ASSETS / 'upstream-tree.json').read_text())
REVISION = TREE['sha']
NAMES = ['40-K Meltagun', 'Autocannon', 'Anti-Materiel Rifle', 'Arc Thrower',
         'Cremator', 'One True Flag', 'CQC-20', None, 'Defoliation Tool',
         'Expendable Anti-Tank', 'EAT-411', 'Expendable Napalm', 'Spear',
         'Flamethrower', 'Grenade Launcher', 'GL-28', 'GL-52 De-Escalator',
         'Recoilless Rifle', 'Laser Cannon', 'Quasar Cannon', 'Maxigun', 'Stalwart',
         'Heavy Machine Gun', 'Machine Gun', 'Bullet Storm', 'Commando', 'Epoch',
         'Airburst Rocket Launcher', 'Railgun', 'Speargun', None,
         'StA-X3 W.A.S.P. Launcher', 'Sterilizer']


def compile_one(pair):
    index, name = pair
    if name is None:
        return index, None, None
    matches = [e['path'] for e in TREE['tree'] if e['path'].endswith('/' + name + '.svg')]
    assert len(matches) == 1, (name, matches)
    url = 'https://raw.githubusercontent.com/nvigneux/Helldivers-2-Stratagems-icons-svg/' + REVISION + '/' + urllib.parse.quote(matches[0])
    raw = urllib.request.urlopen(url, timeout=30).read()
    (ASSETS / f'{index:02}.svg').write_bytes(raw)
    image = Image.open(io.BytesIO(resvg_py.svg_to_bytes(svg_string=raw.decode(), width=128, height=128))).convert('RGBA')
    # Artwork uses transparent backgrounds and white silhouettes.
    rects, active = [], {}
    for y in range(128):
        runs, x = {}, 0
        while x < 128:
            if image.getpixel((x, y))[3] < 128:
                x += 1
                continue
            start = x
            while x < 128 and image.getpixel((x, y))[3] >= 128:
                x += 1
            key = start, x - start
            if key in active:
                r = active.pop(key)
                r[3] += 1
            else:
                r = [start, y, x - start, 1]
            runs[key] = r
        rects.extend(active.values())
        active = runs
    rects.extend(active.values())
    return index, rects, dict(path=matches[0], url=url, sha256=hashlib.sha256(raw).hexdigest())


if __name__ == '__main__':
    ASSETS.mkdir(parents=True, exist_ok=True)
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
        rows = sorted(pool.map(compile_one, enumerate(NAMES, 1)))
    source = ['-- Generated by tools/build_terminal_icons.py. Offline masks; no runtime asset lookup.',
              '-- Artwork: nvigneux/Helldivers-2-Stratagems-icons-svg. See TERMINAL-ICONS.md.', 'return {']
    for index, rectangles, _ in rows:
        if rectangles:
            # Preserve the 64-unit runtime contract with half-unit geometry.
            source.append('[' + str(index) + ']={' + ','.join('{' + ','.join(str(v / 2) for v in r) + '}' for r in rectangles) + '},')
    source.append('}\n')
    (ROOT / 'compat/lll-0.1.14/src/terminal_icons.lua').write_text('\n'.join(source))
    (ASSETS / 'provenance.json').write_text(json.dumps(dict(revision=REVISION, sources={str(i): s for i, _, s in rows if s}), indent=2))
    print('Compiled', sum(r is not None for _, r, _ in rows), 'icons;', sum(len(r or []) for _, r, _ in rows), 'rectangles total; revision', REVISION)
